async function main() {
  console.log('Жылдық жоспарды жаңарту...');
  await prisma.timelineItem.deleteMany();

  for (const item of annualPlanItems) {
    await prisma.timelineItem.create({
      data: item,
    });
    console.log(`✓ Қосылды: [Ай ${item.month}] ${item.titleKk}`);
  }

  console.log('Жылдық жоспар сәтті жаңартылды!');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
